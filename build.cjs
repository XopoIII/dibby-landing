// merged strings for a page: chrome (I18N + EXTRA) + page copy (HUB or a game).
function mergedT(kind, code) {
  const layers = [I18N.en, code !== "en" ? I18N[code] : null, EXTRA.en, code !== "en" ? EXTRA[code] : null];
  if (kind === "__hub__") layers.push(HUB.en, code !== "en" ? HUB[code] : null);
  else { const gc = GAME_COPY[kind] || {}; layers.push(gc.en, code !== "en" ? gc[code] : null); }
  const t = {};
  for (const l of layers) if (l) for (const k in l) if (l[k] != null) t[k] = l[k];
  return t;
}

