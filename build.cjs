#!/usr/bin/env node
/* ============================================================================
   dibby universe landing — static pre-render build.

   WHY: the pages localize via client-side JS (i18n). AI crawlers (GPTBot,
   PerplexityBot, ClaudeBot, …) and most non-Google engines do NOT run JS, so
   this script "bakes" one static HTML file per (page × language) with the text,
   store badges, screenshots and JSON-LD already in the markup.

   STRUCTURE (data-driven from landing/games.config.js):
     /                 → universe hub        (hub.html)
     /<locale>/        → universe hub
     /<slug>/          → a game page         (game.html), e.g. /dibby/, /dash/
     /<locale>/<slug>/ → a game page
   plus legal/utility pages, sitemap, robots, llms.txt, manifest, favicon, 404.

   USAGE:  node build.cjs        → writes ./dist/ (deploy that folder)
   ========================================================================== */
