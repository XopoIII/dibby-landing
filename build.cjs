function sitemap() {
  const entry = (loc, altPairs) => {
    const alts = altPairs.map(([hl, href]) => `    <xhtml:link rel="alternate" hreflang="${hl}" href="${href}" />`).join("\n");
    return `  <url>\n    <loc>${loc}</loc>\n    <lastmod>${PUBLISHER.updated}</lastmod>\n${alts}\n  </url>`;
  };
  const urls = [];
  // hub locales
  const hubAlts = LANGS.map(a => [HREFLANG[a.code], absUrl(hubPath(a.code))]).concat([["x-default", absUrl(hubPath("en"))]]);
  LANGS.forEach(l => urls.push(entry(absUrl(hubPath(l.code)), hubAlts)));
  // each game × locale
  PAGE_GAMES.forEach(g => {
    const alts = LANGS.map(a => [HREFLANG[a.code], absUrl(gamePath(g.slug, a.code))]).concat([["x-default", absUrl(gamePath(g.slug, "en"))]]);
    LANGS.forEach(l => urls.push(entry(absUrl(gamePath(g.slug, l.code)), alts)));
  });
  // legal pages
  LEGAL_SLUGS.forEach(slug => {
    const alts = LEGAL_LANGS.map(c => [HREFLANG[c], legalUrl(slug, c)]).concat([["x-default", legalUrl(slug, "en")]]);
    LEGAL_LANGS.forEach(c => urls.push(entry(legalUrl(slug, c), alts)));
  });
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n${urls.join("\n")}\n</urlset>\n`;
}

