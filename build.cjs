// ---- fs helpers ------------------------------------------------------------
function rmrf(p) { if (fs.existsSync(p)) fs.rmSync(p, { recursive: true, force: true }); }
function copyDir(src, dst) {
  fs.mkdirSync(dst, { recursive: true });
  for (const e of fs.readdirSync(src, { withFileTypes: true })) {
    if (e.name === ".DS_Store") continue;
    if (e.name.endsWith(".ttf")) continue;
    const s = path.join(src, e.name), d = path.join(dst, e.name);
    if (e.isDirectory()) copyDir(s, d); else fs.copyFileSync(s, d);
  }
}
function writePage(dirParts, html, kind, code) {
  const dir = path.join(OUT, ...dirParts);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "index.html"), html);
  fs.writeFileSync(path.join(dir, "i18n.js"), slimI18nJs(kind, code));
}

// ---- build -----------------------------------------------------------------
function build() {
  const hubTpl = fs.readFileSync(path.join(SRC, "hub.html"), "utf8");
  const gameTpl = fs.readFileSync(path.join(SRC, "game.html"), "utf8");
  rmrf(OUT);
  fs.mkdirSync(OUT, { recursive: true });

  copyDir(ASSETS_SRC, path.join(OUT, "assets"));
  CSS_MIN = minifyCss(fs.readFileSync(path.join(SRC, "styles.css"), "utf8"));
  fs.writeFileSync(path.join(OUT, "styles.css"), CSS_MIN);

  // hub: / and /<locale>/
  for (const l of LANGS) {
    const dirParts = l.code === "en" ? [] : [URLCODE[l.code]];
    writePage(dirParts, renderHub(l.code, hubTpl), "__hub__", l.code);
  }
  // game pages: /<slug>/ and /<locale>/<slug>/
  for (const g of PAGE_GAMES) {
    for (const l of LANGS) {
      const dirParts = l.code === "en" ? [g.slug] : [URLCODE[l.code], g.slug];
      writePage(dirParts, renderGame(g, l.code, gameTpl), g.slug, l.code);
    }
  }

  // legal/utility pages
  for (const code of LEGAL_LANGS) {
    for (const slug of LEGAL_SLUGS) {
      const dir = code === "en" ? path.join(OUT, slug) : path.join(OUT, URLCODE[code], slug);
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, "index.html"), renderLegalPage(code, slug));
    }
  }

  fs.writeFileSync(path.join(OUT, "404.html"), render404());
  fs.writeFileSync(path.join(OUT, "favicon.svg"), faviconSvg());
  fs.writeFileSync(path.join(OUT, "site.webmanifest"), webmanifest());
  fs.writeFileSync(path.join(OUT, "sitemap.xml"), sitemap());
  fs.writeFileSync(path.join(OUT, "robots.txt"), robots());
  fs.writeFileSync(path.join(OUT, "llms.txt"), llms());

  for (const f of ["app-ads.txt", "ads.txt"]) {
    const src = path.join(SRC, f);
    if (fs.existsSync(src)) fs.copyFileSync(src, path.join(OUT, f));
  }

  const pages = LANGS.length * (1 + PAGE_GAMES.length);
  console.log(`Built ${pages} pages: hub + ${PAGE_GAMES.length} games (${PAGE_GAMES.map(g => g.slug).join(", ")}) × ${LANGS.length} locales → ${path.relative(ROOT, OUT)}/`);
  console.log(`Legal: ${LEGAL_SLUGS.join(", ")} × ${LEGAL_LANGS.length} locales`);
  if (JSON.stringify(PUBLISHER).includes("[")) console.log("⚠  PUBLISHER still has [placeholders].");
}

