  return str
    .split("{{PUBLISHER_NAME}}").join(escText(PUBLISHER.name))
    .split("{{PUBLISHER_EMAIL}}").join(escText(PUBLISHER.email))
    .split("{{PUBLISHER_ADDRESS}}").join(escText(PUBLISHER.address))
